CREATE TABLE admins (
    id BIGINT NOT NULL,
    totp_secret VARCHAR(100) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE applications (
    applied_at TIMESTAMP(6) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id BIGINT NOT NULL,
    job_seeker_id BIGINT NOT NULL,
    application_status VARCHAR(15) NOT NULL CHECK (
        application_status IN ('UNDER_REVIEW','ACCEPTED','DECLINED')
    ),
    cover_letter VARCHAR(500),
    hr_notes VARCHAR(500),
    PRIMARY KEY (id),
    UNIQUE (job_seeker_id, job_id)
);

CREATE TABLE companies (
    id BIGINT NOT NULL,
    industry_type VARCHAR(15) CHECK (
        industry_type IN ('TECHNOLOGY','HEALTHCARE','EDUCATION','FINANCE','ECOMMERCE','MEDIA','OTHERS')
    ),
    company_name VARCHAR(50),
    logo_image_path VARCHAR(100),
    address VARCHAR(150),
    company_description VARCHAR(500),
    website_url VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE human_resources (
    company_id BIGINT NOT NULL,
    id BIGINT NOT NULL,
    contact VARCHAR(15),
    full_name VARCHAR(50),
    pp_image_path VARCHAR(100),
    PRIMARY KEY (id)
);

CREATE TABLE job_compatible_disabilities (
    job_id BIGINT NOT NULL,
    disability_type VARCHAR(10) NOT NULL CHECK (
        disability_type IN ('VISUAL','HEARING','MOBILITY','COGNITIVE')
    )
);

CREATE TABLE job_seeker_certifications (
    job_seeker_id BIGINT NOT NULL,
    certification_file_path VARCHAR(100) NOT NULL
);

CREATE TABLE job_seeker_skills (
    job_seeker_id BIGINT NOT NULL,
    skill VARCHAR(50) NOT NULL
);

CREATE TABLE job_seekers (
    id BIGINT NOT NULL,
    disability_type VARCHAR(10) CHECK (
        disability_type IN ('VISUAL','HEARING','MOBILITY','COGNITIVE')
    ),
    education_level VARCHAR(20) CHECK (
        education_level IN ('HIGH_SCHOOL','COLLEGE_STUDENT','BACHELOR','MASTER','DOCTORATE')
    ),
    full_name VARCHAR(50),
    cv_document_path VARCHAR(100),
    pp_image_path VARCHAR(100),
    address VARCHAR(150),
    about_me VARCHAR(500),
    PRIMARY KEY (id)
);

CREATE TABLE jobs (
    min_years_experience INTEGER,
    salary NUMERIC(12,2),
    company_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    registration_deadline TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL,
    publication_status VARCHAR(10) NOT NULL CHECK (
        publication_status IN ('OPEN','CLOSED')
    ),
    minimum_education VARCHAR(20) CHECK (
        minimum_education IN ('HIGH_SCHOOL','COLLEGE_STUDENT','BACHELOR','MASTER','DOCTORATE')
    ),
    title VARCHAR(50) NOT NULL,
    job_description VARCHAR(1000),
    PRIMARY KEY (id)
);

CREATE TABLE logs (
    created_at TIMESTAMP(6) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_role VARCHAR(15) NOT NULL,
    action VARCHAR(50) NOT NULL,
    actor_username VARCHAR(50) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE users (
    is_profile_completed BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    updated_at TIMESTAMP(6) NOT NULL,
    role VARCHAR(15) NOT NULL CHECK (
        role IN ('ADMIN','COMPANY','JOB_SEEKER','HUMAN_RESOURCE')
    ),
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    PRIMARY KEY (id)
);

